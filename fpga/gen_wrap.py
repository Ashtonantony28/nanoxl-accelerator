"""Generate rtl/nanoxl_axi_wrap.v from nanoxl_top's port list (SG9a, docs/fpga.md).

    python3 fpga/gen_wrap.py          # rewrite the wrapper after nanoxl_top's ports or parameters change

tests/fpga checks that the checked-in wrapper equals render(), so a port added to nanoxl_top without
regenerating fails a test. Port renames: clk -> aclk, rst_n -> aresetn, <bus>_<sig> -> MAP[bus]_<sig>.
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MAP = {"s_axil": "s_axi_ctrl", "mf_axi": "m_axi_mf", "md_axi": "m_axi_md", "md1_axi": "m_axi_md1"}
PROTO = {"s_axi_ctrl": "PROTOCOL AXI4LITE, DATA_WIDTH 32, ADDR_WIDTH 12",
         "m_axi_mf": "PROTOCOL AXI4, DATA_WIDTH 128, ID_WIDTH 4, READ_WRITE_MODE READ_ONLY",
         "m_axi_md": "PROTOCOL AXI4, DATA_WIDTH 128, ID_WIDTH 4, READ_WRITE_MODE READ_WRITE",
         "m_axi_md1": "PROTOCOL AXI4, DATA_WIDTH 128, ID_WIDTH 4, READ_WRITE_MODE READ_WRITE"}
BUSIF = ":".join(PROTO)


def render(top_text: str | None = None) -> str:
    top = top_text if top_text is not None else (ROOT / "rtl" / "nanoxl_top.sv").read_text()
    hdr = top[top.index("module nanoxl_top"):top.index(");", top.index(") (")) + 2]
    ports = re.findall(r"^\s*(input|output)\s+logic\s*(\[[^\]]+\])?\s*(\w+),?\s*$", hdr, re.M)
    params = re.findall(r"parameter int (\w+)\s*=\s*(\d+),?\s*(//.*)?$", hdr, re.M)
    lines, conns, seen = [], [], set()
    for d, w, n in ports:
        if n == "clk":
            new, attr = "aclk", ('(* X_INTERFACE_INFO = "xilinx.com:signal:clock:1.0 aclk CLK", '
                                 f'X_INTERFACE_PARAMETER = "ASSOCIATED_BUSIF {BUSIF}, ASSOCIATED_RESET aresetn" *)')
        elif n == "rst_n":
            new, attr = "aresetn", ('(* X_INTERFACE_INFO = "xilinx.com:signal:reset:1.0 aresetn RST", '
                                    'X_INTERFACE_PARAMETER = "POLARITY ACTIVE_LOW" *)')
        elif n == "irq":
            new, attr = "irq", ('(* X_INTERFACE_INFO = "xilinx.com:signal:interrupt:1.0 irq INTERRUPT", '
                                'X_INTERFACE_PARAMETER = "SENSITIVITY LEVEL_HIGH" *)')
        else:
            pre, sig = n.rsplit("_", 1)
            bus = MAP[pre]
            new = f"{bus}_{sig}"
            attr = f'(* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 {bus} {sig.upper()}"'
            if bus not in seen:
                seen.add(bus)
                attr += f', X_INTERFACE_PARAMETER = "{PROTO[bus]}"'
            attr += " *)"
        lines.append(f"    {attr}\n    {d:6s} wire {w or '':9s} {new}")
        conns.append(f"        .{n:16s}({new})")
    pl = ",\n".join(f"    parameter integer {k:10s} = {v}" for k, v, c in params)
    pp = ",\n".join(f"        .{k:10s}({k})" for k, v, c in params)
    nl = ",\n"
    return f"""// nanoxl_axi_wrap.v -- Verilog-2001 shell around nanoxl_top for Vivado IP integrator (SG9a, docs/fpga.md).
// GENERATED by fpga/gen_wrap.py from rtl/nanoxl_top.sv; do not edit by hand.
//
// A block design can reference an RTL module only if its top file is Verilog or VHDL, so this file is
// plain Verilog-2001; nanoxl_top and everything below it stay SystemVerilog. The shell adds no logic:
// every port is wired straight through under the AXI names Vivado infers (prefix_SIGNAL), and
// X_INTERFACE_INFO / X_INTERFACE_PARAMETER attributes pin the interfaces explicitly:
//   aclk / aresetn (synchronous, active low = nanoxl_top rst_n), irq (level, active high)
//   s_axi_ctrl  AXI4-Lite slave, 12-bit address (4 KiB CSR window, docs/control.md §5)
//   m_axi_mf    AXI4 read-only master, 128-bit (command fetch)
//   m_axi_md    AXI4 master, 128-bit (DMA channel 0)
//   m_axi_md1   AXI4 master, 128-bit (DMA channel 1, ADR-005)
// tests/fpga checks the names and runs the nanoxl_top smoke test through this shell.
module nanoxl_axi_wrap #(
{pl}
) (
{nl.join(lines)}
);
    nanoxl_top #(
{pp}
    ) u_top (
{nl.join(conns)}
    );
endmodule
"""


if __name__ == "__main__":
    (ROOT / "rtl" / "nanoxl_axi_wrap.v").write_text(render())
